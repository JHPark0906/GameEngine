/// 코드는 답변에 따라 그것을 <b>지우기도</b> 하므로, 시험이 그 자리를 쥐면 언젠가 사용자의
/// 작업을 지운다 — 지금 답하지 않는 시험이라도, 답변 한 줄이 더해지는 날 그렇게 된다.
///
/// 그래서 규칙은 「시험 소스에 GetRecoveryDirectory가 나오지 않는다」이고, 사본을 다루는 모든
/// 함수는 자리를 인자로 받는다. 실행으로는 이 규칙을 잡을 수 없다 — 잘못 쓴 시험은 초록으로
/// 통과하면서 파일을 지우기 때문이다.
/// </summary>
[[nodiscard]] bool RunRecoveryDirectoryRuleTests();
